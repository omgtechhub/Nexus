#!/usr/bin/env bash
#
# Issue and auto-renew a Let's Encrypt certificate for this deployment.
#
# nginx.conf reads a fixed pair of filenames, origin.pem and origin.key, out of
# TLS_CERT_DIR (default ./certs) — a shape that came from Cloudflare Origin
# Certificates, which never expire and are copied in by hand once. Let's
# Encrypt certificates expire every 90 days, so the copy has to happen again on
# every renewal or the site starts serving an expired certificate roughly three
# months after launch, when nobody is thinking about it any more.
#
# So this installs a deploy hook rather than just copying the files: certbot's
# timer renews, the hook re-copies under the names nginx expects and reloads
# it. Renewal is then genuinely unattended.
#
# certbot runs --standalone, which needs port 80 to itself, so the hooks stop
# and start the frontend container around it. The alternative, --webroot
# through the running nginx, would mean mounting a challenge directory into the
# container and adding a location block to serve it: more moving parts in the
# web server config, which is the thing that must not break.
#
# Usage:  sudo ./scripts/setup-tls.sh nexus.duckdns.org you@example.com
set -euo pipefail

DOMAIN="${1:?usage: setup-tls.sh <domain> <email>}"
EMAIL="${2:?usage: setup-tls.sh <domain> <email>}"

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CERT_DIR="${TLS_CERT_DIR:-$REPO_DIR/certs}"

# Resolve the invoking user's compose context. Run under sudo, $HOME and the
# docker group belong to root, but the stack was brought up as the login user.
COMPOSE_USER="${SUDO_USER:-$USER}"

echo "==> Installing certbot"
apt-get update -qq
apt-get install -y -qq certbot

mkdir -p "$CERT_DIR"

echo "==> Installing renewal deploy hook"
HOOK=/etc/letsencrypt/renewal-hooks/deploy/nexus-copy-certs.sh
mkdir -p "$(dirname "$HOOK")"
cat > "$HOOK" <<HOOK_BODY
#!/usr/bin/env bash
# Generated by scripts/setup-tls.sh. Runs after every successful renewal.
set -euo pipefail

# Only act on this deployment's certificate. certbot runs every deploy hook for
# every renewed lineage, so a second certificate on this host would otherwise
# overwrite these files with the wrong domain's key.
[ "\$RENEWED_LINEAGE" = "/etc/letsencrypt/live/$DOMAIN" ] || exit 0

install -m 644 "\$RENEWED_LINEAGE/fullchain.pem" "$CERT_DIR/origin.pem"
install -m 600 "\$RENEWED_LINEAGE/privkey.pem"   "$CERT_DIR/origin.key"

# Reload rather than restart: an in-place reload re-reads the certificate
# without dropping the connections currently being served.
cd "$REPO_DIR"
sudo -u "$COMPOSE_USER" docker compose exec -T frontend nginx -s reload 2>/dev/null \
  || sudo -u "$COMPOSE_USER" docker compose restart frontend
HOOK_BODY
chmod +x "$HOOK"

echo "==> Requesting certificate for $DOMAIN"
# Free port 80 for the standalone challenge responder, if the stack is already up.
cd "$REPO_DIR"
sudo -u "$COMPOSE_USER" docker compose stop frontend 2>/dev/null || true

certbot certonly \
  --standalone \
  --non-interactive \
  --agree-tos \
  --email "$EMAIL" \
  --domain "$DOMAIN" \
  --pre-hook  "cd $REPO_DIR && sudo -u $COMPOSE_USER docker compose stop frontend  || true" \
  --post-hook "cd $REPO_DIR && sudo -u $COMPOSE_USER docker compose start frontend || true"

# The deploy hook does not fire on first issuance, only on renewal, so place the
# files once by hand here.
install -m 644 "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" "$CERT_DIR/origin.pem"
install -m 600 "/etc/letsencrypt/live/$DOMAIN/privkey.pem"   "$CERT_DIR/origin.key"

sudo -u "$COMPOSE_USER" docker compose start frontend 2>/dev/null || true

echo
echo "Certificate installed:"
echo "  $CERT_DIR/origin.pem"
echo "  $CERT_DIR/origin.key"
echo
echo "Renewal is handled by certbot's systemd timer. Verify it with:"
echo "  sudo certbot renew --dry-run"
